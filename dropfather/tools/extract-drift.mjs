// Takes DRIFT SONATA's sound engine into Dropfather: its WASM synth, its choir and cello recordings and its 111
// sounds (the 15 presets and their variations, made by DriftSonata's own code). The page, its chord lines,
// keyboard and drums stay in DriftSonata.
// Usage: node tools/extract-drift.mjs DriftSonata.html  → src/vendor/drift-data.js
import fs from 'node:fs';
import path from 'node:path';

const src = fs.readFileSync(process.argv[2], 'utf8');
const lineOf = name => { const m = new RegExp(`const ${name} = (.*);\\s*$`, 'm').exec(src); if (!m) throw Error(name + ' not found'); return m[1]; };
const DATA = JSON.parse(lineOf('DATA')), WASM_B64 = JSON.parse(lineOf('WASM_B64')), SAMPLES = JSON.parse(lineOf('SAMPLES'));
// DriftSonata's sound bank: presetValuesOf … soundValues, run as they are.
const a = src.indexOf('function presetValuesOf'), b = src.indexOf('\n}', src.indexOf('function soundValues')) + 2;
const rng = src.match(/const rng32 = seed => \(\) => \{.*?\};/)[0];
const bank = Function('DATA', `${rng}\nconst P=DATA.params,idx={};P.forEach((p,i)=>idx[p.id]=i);const DEFAULTS=P.map(p=>p.def);\n${src.slice(a, b)}\nreturn soundBank.map(s=>({name:s.name,group:s.base.group,values:soundValues(s)}));`)(DATA);

const out = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'src', 'vendor', 'drift-data.js');
fs.writeFileSync(out, `/* From DRIFT SONATA by Tarjei Krogh: its synth engine (WASM), choir and cello recordings and 111 sounds. Generated by tools/extract-drift.mjs. */\n` +
  `window.DRIFT_DATA=${JSON.stringify({ ids: DATA.params.map(p => p.id), sounds: bank })};\nwindow.DRIFT_WASM_B64=${JSON.stringify(WASM_B64)};\nwindow.DRIFT_SAMPLES=${JSON.stringify(SAMPLES.map(s => ({ fam: s.fam, root: s.root, b64: s.b64 })))};\n`);
console.log(bank.length, 'sounds,', DATA.params.length, 'params,', SAMPLES.length, 'recordings →', out, (fs.statSync(out).size / 1e6).toFixed(2), 'MB');
