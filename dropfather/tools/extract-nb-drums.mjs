// Pulls Stanley Cupid's own drum recordings and kits out of Norwegian Beats into src/vendor/nb-drums.js.
// Usage: node tools/extract-nb-drums.mjs Norwegian_Beats.html assets-1.js assets-2.js assets-3.js
// Kits: the sample kits (SKITS) and the named acoustic kits (Pocket 93, Broken 78, Groovy 102).
// Left out: the mouth kit and the user bank (breakbeat drums of unknown origin).
import fs from 'node:fs';
import path from 'node:path';

const [html, ...assetFiles] = process.argv.slice(2);
if (!html || !assetFiles.length) { console.error('usage: extract-nb-drums.mjs Norwegian_Beats.html assets-*.js'); process.exit(1); }
const src = fs.readFileSync(html, 'utf8');
const assets = {};
for (const f of assetFiles) for (const m of fs.readFileSync(f, 'utf8').matchAll(/NB_ASSETS\[(\d+)\]="([^"]*)"/g)) assets[m[1]] = m[2];

// Object literal → value, only for plain data (no identifiers that are not keys).
function literal(text) {
  if (/[()`;]|=>|function/.test(text)) throw Error('not a plain literal: ' + text.slice(0, 80));
  return Function('return (' + text + ')')();
}
function block(from) {
  let depth = 0, quote = null;
  for (let i = from; i < src.length; i++) {
    const c = src[i];
    if (quote) { if (c === '\\') i++; else if (c === quote) quote = null; continue; }
    if (c === '"' || c === "'") quote = c;
    else if (c === '{' || c === '[') depth++;
    else if (c === '}' || c === ']') { depth--; if (!depth) return src.slice(from, i + 1); }
  }
  throw Error('unclosed block at ' + from);
}

// One sound by id: name, level, data. Data is inline base64 or NB_ASSETS[n].
function sound(id) {
  const m = new RegExp(`(?<![\\w"])"?${id}"?:\\{`).exec(src);
  if (!m) throw Error('sound not found: ' + id);
  const head = src.slice(m.index + m[0].length - 1, m.index + m[0].length + 400);
  const n = /"?n"?:\s*['"]([^'"]+)['"]/.exec(head)[1], lane = /"?lane"?:\s*['"](\w+)['"]/.exec(head)[1], g = +/"?g"?:\s*([\d.]+)/.exec(head)[1];
  const re = /[{,]\s*"?d"?:\s*(?:NB_ASSETS\[(\d+)\]|(['"]))/g;
  re.lastIndex = m.index + m[0].length - 1;
  const r = re.exec(src);
  const d = r[1] ? assets[r[1]] : src.slice(re.lastIndex, src.indexOf(r[2], re.lastIndex));
  if (!d) throw Error('no data for ' + id);
  const bytes = Buffer.from(d.slice(0, 16), 'base64');
  const mime = bytes.slice(0, 4).toString() === 'fLaC' ? 'audio/flac' : bytes.slice(4, 8).toString() === 'ftyp' ? 'audio/mp4' : bytes.slice(0, 4).toString() === 'RIFF' ? 'audio/wav' : 'audio/mpeg';
  return { n, lane, g, mime, d };
}

const skits = literal(block(src.indexOf('{', src.indexOf('const SKITS='))));
const acoustic = [...src.matchAll(/\{"n":"(Pocket 93|Broken 78|Groovy 102)","kick":"[^}]*\}/g)].map(m => JSON.parse(m[0]));
// Acoustic kits have no clap: each gets one of the clap recordings.
const acousticClap = { 'Pocket 93': 'lovely', 'Broken 78': 'group', 'Groovy 102': 'wide' };

const kits = [];
for (const [id, k] of Object.entries(skits)) {
  if (id === 'mouth') continue;
  const L = {};
  for (const [lane, [s, pitch = 0, , layer, layerLevel = 0, layerPitch = 0]] of Object.entries(k.L)) {
    const to = { kick: 'kick', snare: 'snare', clap: 'clap', hat: 'hat', ohat: 'open' }[lane];
    if (to) L[to] = layer ? [s, pitch, layer, layerLevel, layerPitch] : pitch ? [s, pitch] : [s];
  }
  kits.push({ id, n: k.n, L });
}
for (const k of acoustic) kits.push({ id: k.n.toLowerCase().replace(/\s+/g, ''), n: k.n, L: { kick: [k.kick], clap: [acousticClap[k.n]], snare: [k.snare], hat: [k.hat], open: [k.ohat] } });

const sounds = {};
for (const k of kits) for (const [s, , layer] of Object.values(k.L)) for (const id of [s, layer]) if (id && !sounds[id]) sounds[id] = sound(id);

const out = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'src', 'vendor', 'nb-drums.js');
fs.writeFileSync(out, `/* Drum kits from Norwegian Beats: Stanley Cupid's own recordings (Tarjei Krogh). Generated by tools/extract-nb-drums.mjs. */\nwindow.NB_DRUMS=${JSON.stringify({ kits, sounds })};\n`);
const size = Object.values(sounds).reduce((a, s) => a + s.d.length, 0);
console.log(kits.length, 'kits,', Object.keys(sounds).length, 'sounds,', (size / 1e6).toFixed(2), 'MB base64 →', out);
