// Takes VOXY MUSIC's vocal engine into Dropfather as an insert on audio tracks: its AudioWorklet (vocoders,
// 201 Machine, Second Voice, the DELAYSY vocal effects), its HRTF stereo doubles and effect space, its 32 factory
// presets and the DELAYSY effect settings they use. Module files are joined as they are, each in its own scope;
// the one change: the worklet also takes its settings in processorOptions, so an offline render starts on time.
// Usage: node tools/extract-voxy.mjs VOXY-MUSIC-v0.7/dist  → src/vendor/voxy-worklet.js (text), src/vendor/voxy.js
import fs from 'node:fs';
import path from 'node:path';

const dist = process.argv[2], read = f => fs.readFileSync(path.join(dist, f), 'utf8');
// One ES module → a scoped block that hands back its exports.
function scoped(file) {
  let code = read(file).replace(/^\s*import [^;]*;\s*$/gm, '');
  const names = [...code.matchAll(/export\s+(?:const|class|function)\s+([A-Za-z_$][\w$]*)/g)].map(m => m[1]);
  code = code.replace(/export\s+(const|class|function)\s/g, '$1 ');
  return `const {${names.join(',')}}=(()=>{\n${code}\nreturn {${names.join(',')}};\n})();`;
}
let engine = read('voice-engine.js').replace(/^\s*import [^;]*;\s*$/gm, '');
const a = 'constructor(){super();', b = 'this.lastStep=-1;this.port.onmessage';
if (engine.split(a).length !== 2 || engine.split(b).length !== 2) throw Error('voice-engine.js changed: update the patch');
engine = engine.replace(a, 'constructor(options){super();const __o=options&&options.processorOptions;')
  .replace(b, 'this.lastStep=-1;if(__o){Object.assign(this.p,__o);this.second.configure(this.p);this.effect.configure(this.p.effectSettings||{},this.p.bpm);}this.port.onmessage');
const worklet = ['delaysy-vocal.js', 'vsm201-core.js', 'vocoder-core.js', 'second-voice-core.js', 'effect-core.js'].map(scoped).join('\n') + '\n' + engine;

// Presets and the effect settings they point to (not the whole 777 bank).
const presetMod = {}; Function('out', scoped('preset-bank.js') + '\nout.defaults=defaults;out.factoryPresets=factoryPresets;')(presetMod);
const fx = {}; Function('out', scoped('effect-bank.js') + '\nout.factoryEffects=factoryEffects;')(fx);
const used = [...new Set(presetMod.factoryPresets.map(p => +p.settings.effectPreset || 0))];
const effects = Object.fromEntries(used.map(i => [i, fx.factoryEffects[i].p]));

const outDir = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'src', 'vendor');
fs.writeFileSync(path.join(outDir, 'voxy-worklet.js'), `// VOXY MUSIC 0.7 by Tarjei Krogh: its AudioWorklet engine, joined by tools/extract-voxy.mjs.\n${worklet}\n`);
fs.writeFileSync(path.join(outDir, 'voxy.js'), `/* VOXY MUSIC 0.7 by Tarjei Krogh: stereo doubles, effect space, 32 factory presets and their DELAYSY effect settings. Generated by tools/extract-voxy.mjs. */
(function(root){
${scoped('stereo-vocals.js')}
${scoped('effect-space.js')}
root.VOXY={StereoVocals,EffectSpace,defaults:${JSON.stringify(presetMod.defaults)},presets:${JSON.stringify(presetMod.factoryPresets)},effects:${JSON.stringify(effects)}};
})(window);
`);
console.log(presetMod.factoryPresets.length, 'presets,', used.length, 'effect settings, worklet', worklet.length, 'chars');
